/**
 * Resolves the configuration for a given industry string, falling back to 'other'
 */
export function getIndustryImportTemplate(rawIndustry?: string): IndustryTemplateConfig {
  const norm = String(rawIndustry || '').toLowerCase().trim();
  if (norm.includes('pharma') || norm.includes('chem') || norm.includes('medic')) {
    return INDUSTRY_IMPORT_TEMPLATES.pharmacy;
  }
  if (norm.includes('cloth') || norm.includes('apparel') || norm.includes('garment') || norm.includes('fashion')) {
    return INDUSTRY_IMPORT_TEMPLATES.clothing;
  }
  if (norm.includes('elect') || norm.includes('tech') || norm.includes('gadget') || norm.includes('mobile')) {
    return INDUSTRY_IMPORT_TEMPLATES.electronics;
  }
  if (norm.includes('groc') || norm.includes('supermarket') || norm.includes('food') || norm.includes('fmcg')) {
    return INDUSTRY_IMPORT_TEMPLATES.grocery;
  }
  if (norm.includes('hard') || norm.includes('tool') || norm.includes('steel') || norm.includes('plumb')) {
    return INDUSTRY_IMPORT_TEMPLATES.hardware;
  }
  if (norm.includes('auto') || norm.includes('vehicle') || norm.includes('car') || norm.includes('motor')) {
    return INDUSTRY_IMPORT_TEMPLATES.automobile;
  }
  return INDUSTRY_IMPORT_TEMPLATES.other;
}

/**
 * Escapes a cell value for standard CSV formatting (RFC 4180)
 */
function escapeCsvCell(val: any): string {
  if (val === null || val === undefined) return '';
  const str = String(val);
  if (str.includes(',') || str.includes('"') || str.includes('\n') || str.includes('\r')) {
    return `"${str.replace(/"/g, '""')}"`;
  }
  return str;
}

/**
 * Generates ready-to-download CSV template text, filename, and column list
 */
export function generateIndustryCsvTemplate(
  rawIndustry?: string,
  businessName?: string
): { filename: string; csvContent: string; headers: string[]; config: IndustryTemplateConfig } {
  const config = getIndustryImportTemplate(rawIndustry);
  const headers = config.columns.map((c) => c.header);
  const headerLine = headers.map(escapeCsvCell).join(',');

  const rowsLines = config.sampleRows.map((row) => {
    return config.columns.map((col) => escapeCsvCell(row[col.key] ?? '')).join(',');
  });

  const csvContent = [headerLine, ...rowsLines].join('\n') + '\n';
  const cleanBizName = businessName ? `_${businessName.toLowerCase().replace(/[^a-z0-9]+/g, '_').slice(0, 20)}` : '';
  const filename = `${config.filenamePrefix}${cleanBizName}.csv`;

  return { filename, csvContent, headers, config };
}

